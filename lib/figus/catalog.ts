export const TOTAL_STICKERS = STICKER_CATALOG.length;

export const STICKER_BY_ORDINAL = new Map(STICKER_CATALOG.map((sticker) => [sticker.ordinal, sticker]));
export const STICKER_BY_CODE = new Map(STICKER_CATALOG.map((sticker) => [sticker.code.toUpperCase(), sticker]));

export const STICKER_SECTIONS = Array.from(new Set(STICKER_CATALOG.map((sticker) => sticker.section)));


export function stickerTeamTitle(sticker: StickerEntry) {
  if (sticker.team.length === 3 && sticker.group !== "FWC" && sticker.group !== "CC") {
    return `${sticker.teamName} (${sticker.team})`;
  }
  return sticker.teamName;
}

export function stickerDisplayName(value?: number | null) {
  if (!value) return "";
  const sticker = STICKER_BY_ORDINAL.get(value);
  if (!sticker) return String(value);

  if (sticker.team.length === 3 && sticker.group !== "FWC" && sticker.group !== "CC") {
    return `${sticker.teamName} (${sticker.team}) · ${sticker.code}`;
  }

  return sticker.code;
}

export function stickerCode(value?: number | null) {
  if (!value) return "";
  return STICKER_BY_ORDINAL.get(value)?.code ?? String(value);
}

export function stickerLabel(value?: number | null) {
  if (!value) return "";
  const sticker = STICKER_BY_ORDINAL.get(value);
  if (!sticker) return String(value);
  return `${sticker.flag} ${stickerDisplayName(value)}`;
}

export function stickerFromCode(code: string) {
  return STICKER_BY_CODE.get(code.trim().toUpperCase()) ?? null;
}

export function stickersBySection(section: string) {
  return STICKER_CATALOG.filter((sticker) => sticker.section === section);
}

export function stickersByTeam(team: string) {
  return STICKER_CATALOG.filter((sticker) => sticker.team === team);
}

export function groupedStickerCatalog() {
  const sections = new Map<string, Map<string, StickerEntry[]>>();

  for (const sticker of STICKER_CATALOG) {
    if (!sections.has(sticker.section)) sections.set(sticker.section, new Map());
    const teams = sections.get(sticker.section)!;
    const key = sticker.team;
    if (!teams.has(key)) teams.set(key, []);
    teams.get(key)!.push(sticker);
  }

  return Array.from(sections.entries()).map(([section, teams]) => ({
    section,
    teams: Array.from(teams.entries()).map(([team, stickers]) => ({
      team,
      teamName: stickers[0]?.teamName ?? team,
      flag: stickers[0]?.flag ?? "",
      stickers,
    })),
  }));
}

export function parseStickerToken(token: string): number | null {
  const clean = token.trim().toUpperCase();
  if (!clean) return null;

  const byCode = STICKER_BY_CODE.get(clean);
  if (byCode) return byCode.ordinal;

  const numeric = Number(clean.replace(/[^0-9]/g, ""));
  if (Number.isInteger(numeric) && numeric >= 1 && numeric <= TOTAL_STICKERS) return numeric;

  return null;
}

export function parseStickerInput(value: string): number[] {
  const out: number[] = [];
  const tokens = value.split(/[\s,;|/\\]+/).map((t) => t.trim()).filter(Boolean);

  for (const token of tokens) {
    const range = token.toUpperCase().match(/^([A-Z]{2,4})(\d+)\s*-\s*([A-Z]{2,4})?(\d+)$/);
    if (range) {
      const prefixA = range[1];
      const start = Number(range[2]);
      const prefixB = range[3] || prefixA;
      const end = Number(range[4]);

      if (prefixA === prefixB) {
        const a = Math.min(start, end);
        const b = Math.max(start, end);
        for (let n = a; n <= b; n++) {
          const sticker = STICKER_BY_CODE.get(`${prefixA}${n}`);
          if (sticker) out.push(sticker.ordinal);
        }
        continue;
      }
    }

    const parsed = parseStickerToken(token);
    if (parsed) out.push(parsed);
  }

  return Array.from(new Set(out)).sort((a, b) => a - b);
}

export function parseStickerCounts(value: string): Record<number, number> {
  const counts: Record<number, number> = {};
  const tokens = value.split(/[\s,;|/\\]+/).map((t) => t.trim()).filter(Boolean);

  for (const token of tokens) {
    const multi = token.toUpperCase().match(/^([A-Z]{2,4}\d+|\d+)\s*(?:X|\*)\s*(\d+)$/);
    if (multi) {
      const ordinal = parseStickerToken(multi[1]);
      const quantity = Number(multi[2]);
      if (ordinal && quantity > 0) counts[ordinal] = (counts[ordinal] ?? 0) + quantity;
      continue;
    }

    const ordinal = parseStickerToken(token);
    if (ordinal) counts[ordinal] = (counts[ordinal] ?? 0) + 1;
  }

  return counts;
}

export function formatStickerList(values?: number[] | null, limit = 12) {
  const list = (values ?? []).map(stickerCode);
  const visible = list.slice(0, limit).join(", ");
  const rest = list.length > limit ? ` +${list.length - limit} más` : "";
  return visible ? `${visible}${rest}` : "—";
}
